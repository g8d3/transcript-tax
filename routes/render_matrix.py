#!/usr/bin/env python3
"""Render MATRIX.md from matrix.json — every number in the document comes from a measured run."""
from __future__ import annotations
import json
import re
import statistics
import sys
from collections import defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from matrix import price_of  # noqa: E402  (one price heuristic, not two)

HERE = Path(__file__).parent
rows = json.loads((HERE / "matrix.json").read_text())
ok = [r for r in rows if r["state"] == "ok"]
bad = [r for r in rows if r["state"] != "ok"]

def catalog_groups() -> list[tuple[float, str, list[tuple[str, str, float, float | None]]]]:
    """Base model -> every route that carries it, with the spread in published input price.

    Matching rule (stated on the page too): drop the vendor prefix, drop `:batch`/async
    tiers (a different product), drop the `-TEE`/`-turbo`/`-preview`/`-fast`/`-free`
    deployment suffixes, then compare what is left. Only groups with at least two
    *providers* that publish a price are reported, and the comparison is between prices
    each provider publishes itself.
    """
    models = json.loads((HERE / "models.json").read_text())
    groups: dict[str, list] = defaultdict(list)
    for provider, meta in models.items():
        if meta.get("state") != "ok":
            continue
        for model_id in (meta.get("priced") or {}):
            if ":" in model_id:
                continue
            price = price_of(provider, model_id)
            if price and price[0]:
                groups[norm_model(model_id)].append((provider, model_id, price[0], price[1]))
    rows = []
    for name, routes in groups.items():
        if len({p for p, _, _, _ in routes}) < 2:
            continue
        ins = [r[2] for r in routes]
        rows.append((max(ins) / min(ins), name, sorted(routes, key=lambda r: r[2])))
    return sorted(rows, reverse=True)


def norm_model(name: str) -> str:
    # dot and hyphen are the same separator: one provider sells `claude-sonnet-5.5` and
    # another `claude-sonnet-5-5`, and the matrix has to group them as one model.
    n = name.split("/")[-1].lower()
    n = re.sub(r"-(tee|turbo|fast|preview|free|contributor)$", "", n)
    n = n.replace("_", "-")
    return re.sub(r"[^a-z0-9]+", "-", n).strip("-")


def cache_rows() -> list[dict]:
    """The cache probe rows (routes/cache.json), or [] if the probe has not been run."""
    path = HERE / "cache.json"
    return json.loads(path.read_text()) if path.exists() else []


def money(v):
    return "–" if v is None else f"${v:g}"

out = ["# Provider matrix — the same model, several routes",
       "",
       "Generated by `render_matrix.py` from `matrix.json` (raw calls in `matrix.py`, config in",
       "`routes.json`). Prices are the ones **each provider publishes in its own `/models` metadata**;",
       "`–` means that API publishes no price and we do not guess one. Latency is measured here, streaming,",
       "median of 2 reps on one machine: **first token** and **total**, the same split the monitor makes",
       "(`preResponseMs` vs the model span).",
       "",
       "| anchor | route | $/M in | $/M out | $/M cache-read | first token p50 | total p50 | streamed |",
       "|---|---|---|---|---|---|---|---|"]
for r in sorted(ok, key=lambda r: (r["anchor"], r["provider"])):
    pin, pout, pcache = (r["price"] or (None, None, None))
    # a route that answered in one chunk has no measurable first token: the cell must read "–",
    # not "None ms" (it did, on the published page, for gemini-3-flash-preview / gemini).
    def ms(v: object) -> str:
        return "–" if v is None else f"{v} ms"

    out.append(f"| {r['anchor']} | {r['provider']} | {money(pin)} | {money(pout)} | {money(pcache)} | "
               f"{ms(r['ttft_p50'])} | {ms(r['total_p50'])} | "
               f"{'yes' if r.get('streamed') else 'no'} |")
if bad:
    out += ["", "## Routes that exist but could not answer", "",
            "| anchor | route | why |", "|---|---|---|"]
    for r in bad:
        why = r.get("error") or r.get("state")
        why = (why or "").replace("|", "/")[:110]
        out.append(f"| {r['anchor']} | {r['provider']} | {why} |")

# dispersion, computed from the table (not typed by hand)
out += ["", "## What the table says", ""]
for anchor in sorted({r["anchor"] for r in ok}):
    pr = [(r["provider"], r["price"][0]) for r in ok
          if r["anchor"] == anchor and r["price"] and r["price"][0]]
    lo = hi = None
    if len(pr) > 1:
        lo = min(pr, key=lambda t: t[1]); hi = max(pr, key=lambda t: t[1])
        if hi[1] == lo[1]:
            out.append(f"- **{anchor}**: every priced route charges the same list price "
                       f"({money(lo[1])}/M in) — the difference shows up in latency, not in the rate.")
        else:
            out.append(f"- **{anchor}**: input price runs {hi[1]/lo[1]:.1f}x between routes "
                       f"({lo[0]} {money(lo[1])}/M vs {hi[0]} {money(hi[1])}/M).")
    lat = {r["provider"]: r["ttft_p50"] for r in ok if r["anchor"] == anchor and r["ttft_p50"]}
    if len(lat) > 1:
        fast = min(lat, key=lat.get); slow = max(lat, key=lat.get)
        cheapest = lo[0] if lo else None
        verdict = ("the cheapest route is also the fastest one here"
                   if cheapest == fast else
                   f"the cheapest priced route ({cheapest}) is not the fastest one"
                   if cheapest else "prices are not published for most of these routes")
        out.append(f"- **{anchor}**: first token {lat[fast]} ms on {fast} vs {lat[slow]} ms on {slow} "
                   f"({lat[slow]/lat[fast]:.1f}x) — {verdict}.")
out += ["",
        "Route mechanics measured while building this (all of it is product-relevant, because the",
        "route is part of what the audit measures):",
        "",
        "- **`opencode-go` is not a bare OpenAI-compatible endpoint.** A key-only call returns",
        "  `400 MissingSessionID — Request is missing x-opencode-session and cannot be routed`. It routes",
        "  by harness session, so a session id is part of the route; the matrix sends one.",
        "- **Two routes are funded nowhere:** `aihubmix` answers `403 account balance is insufficient` and",
        "  `cerebras` answers `402 payment required`. They are listed above as unavailable, not as options.",
        "- **Cache-read pricing is a route property, not a model property** (same model family:",
        "  $0.0016/M on one route, $0.044/M on another), so the cache lever is worth what the route charges",
        "  for it.",
        "- Several routes return the reply inside a `reasoning_content` field instead of `content`, and some",
        "  deliver it in a single chunk (no measurable first token). That is the same artifact that forced",
        "  our own rate floor (`minStreamMs`, e10.3): a window you cannot measure is not a rate.",
        "",
        "## The catalog: the same base model, every route that carries it",
        "",
        "Computed by the same script from the `/models` metadata of every provider we hold a key for",
        f"(`routes/models.json`: {sum(len(v.get('ids') or []) for v in json.loads((HERE / 'models.json').read_text()).values() if v.get('state') == 'ok')} model ids across the providers that answered). Matching rule: vendor prefix dropped, `:batch`/async",
        "tiers excluded (a different product), deployment suffixes (`-TEE`, `-turbo`, `-preview`,",
        "`-fast`, `-free`) stripped, then compared — so a row can compare a plain endpoint against a",
        "TEE deployment of the same base model, and it says so rather than pretending they are the",
        "same artifact.",
        "",
        "| base model | routes that publish a price (input $/M) | spread |",
        "|---|---|---|"]
catalog = catalog_groups()
for ratio, name, routes in catalog[:12]:
    cells = ", ".join(f"{p} {money(i)}" for p, _, i, _ in routes)
    out.append(f"| {name} | {cells} | {ratio:.2f}x |")
if catalog:
    ratios = [r for r, _, _ in catalog]
    out += ["",
            f"**{len(catalog)} base models are carried by more than one of our routes with a published",
            f"price.** Median spread {statistics.median(ratios):.2f}x, p90 "
            f"{sorted(ratios)[int(0.9 * len(ratios))]:.2f}x, worst {max(ratios):.2f}x. So the honest",
            "version of the pitch is not \"everything is 20x cheaper elsewhere\": for most models the",
            "list price is the same everywhere and the difference shows up in latency; the price spread",
            "lives in a handful of routes, and finding them is the work.",
            ""]
out += ["",
        "## Does the prefix cache engage on each route?",
        "",
        "Two identical ~4k-token prompts, back to back, one pair per route. `cached` is what the",
        "provider itself reports in `prompt_tokens_details.cached_tokens` on the second call, and the",
        "wall delta is second minus first. **A miss here means no hit was observed in this probe, not",
        "that caching is off** — one pair of calls cannot prove the latter, and a provider that does not",
        "report the field is indistinguishable from one that does not cache. That distinction is worth",
        "money, so it is stated rather than resolved.",
        "",
        "| model | route | input tokens | cached (reported) | cached share | total, 1st → 2nd |",
        "|---|---|---|---|---|---|"]
cache = cache_rows()
for r in cache:
    if r.get("state") != "ok":
        out.append(f"| {r['anchor']} | {r['provider']} | – | – | – | {(r.get('error') or '')[:60]} |")
        continue
    sec = r["second"]
    share = "–" if r.get("cached_share") is None else f"{r['cached_share']*100:.1f}%"
    out.append(f"| {r['anchor']} | {r['provider']} | {sec.get('in_tokens')} | "
               f"{sec.get('cached_tokens')} | {share} | {r['first']['total_ms']} → {sec['total_ms']} ms |")
hits = [r for r in cache if r.get("state") == "ok" and r.get("hit")]
misses = [r for r in cache if r.get("state") == "ok" and not r.get("hit")]
failed = [r for r in cache if r.get("state") != "ok"]
if cache:
    out += ["",
            f"**{len(hits)} of {len(hits) + len(misses)} probed routes reported a cache hit** on the",
            "second call." + (" The ones that did not: " +
                              ", ".join(f"`{r['provider']}` on {r['anchor']}" for r in misses) +
                              f" — for {sum(1 for r in misses if any(h['anchor'] == r['anchor'] and h['provider'] != r['provider'] for h in hits))}"
                              " of them the same base model reported a hit on a different route, so"
                              " caching is a property of the route as much as of the model. A route that"
                              " does not report the field looks exactly like one that does not cache,"
                              " which is why the audit measures the client's own loops instead of trusting"
                              " a vendor table." if misses else
                              " Every route we could probe cached something."),
            (f" ({len(failed)} route(s) could not answer: " +
             ", ".join(f"`{r['provider']}`" for r in failed) + ".)" if failed else ""),
            ""]
out += ["",
        "**Limits.** n=2 per route on one machine, one prompt (a one-word reply), so this is a",
        "route-dispersion probe, not a benchmark; `-TEE` variants are the same base model served under a",
        "different deployment, which may include a different quantization — we label them by their own id",
        "rather than pretending they are identical artifacts. Prices rotate: re-run `matrix.py` before",
        "quoting any row.",
        ""]
if __name__ == "__main__":  # importing this module (the page test does) must not rewrite the file
    (HERE / "MATRIX.md").write_text("\n".join(out))
    print(f"wrote MATRIX.md ({len(ok)} ok rows, {len(bad)} unavailable)")
